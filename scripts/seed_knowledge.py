def run():
    print("Seeding Chulalongkorn Sepsis Handbook (guid.md) into Knowledge Base...")
    for cat_data in CATEGORIES:
        category, _ = KnowledgeCategory.objects.update_or_create(
            slug=cat_data["slug"],
            defaults={
                "name": cat_data["name"],
                "icon": cat_data["icon"],
                "order": cat_data["order"]
            }
        )
        print(f"Category: {category.name}")

    # Remove categories that are no longer part of the taxonomy (old 7-category split)
    valid_slugs = [c["slug"] for c in CATEGORIES]
    stale_categories = KnowledgeCategory.objects.exclude(slug__in=valid_slugs)
    if stale_categories.exists():
        print(f"Removing {stale_categories.count()} stale categories: {list(stale_categories.values_list('slug', flat=True))}")
        stale_categories.delete()

    for art_data in ARTICLES:
        try:
            category = KnowledgeCategory.objects.get(slug=art_data["category_slug"])
            article, created = KnowledgeArticle.objects.update_or_create(
                title=art_data["title"],
                defaults={
                    "category": category,
                    "summary": art_data["summary"],
                    "content": art_data["content"],
                    "send_schedule": art_data["send_schedule"],
                    "is_published": True
                }
            )
            print(f"Article: {article.title} (Created: {created})")
        except Exception as e:
            print(f"Error creating article {art_data['title']}: {e}")

if __name__ == '__main__':
    run()
